"use strict";

// エピソードを指す短い id。
//
//
// ■ 何から作るか
//
// フィードの guid。番組がその回を一意に指すために持っている値で、配信中の
// 234フィード・23,723話のうち 99.9% が持っている。番組が guid を変えない
// 限り、新しい回が増えても古い回が落ちても値は変わらない。
//
// 通し番号は使えない。フィードは新しい回が先頭に足されるので、先頭から
// 数えると番号がずれて、同じ id が別の回を指してしまう。末尾から数える手も
// あるが、古い回をフィードから落とす番組があり、そちらもずれる。
//
// guid を持たない番組がわずかにあるので（1フィード・19話）、呼ぶ側が
// エピソードのページ URL、それも無ければ音声の URL まで下がって代える
// （scripts/fetch-feeds.js の toEpisode）。
//
//
// ■ どう畳むか
//
// guid は URL のことが多く、長さは中央値36文字・最長246文字ある。URL に
// 載せるには長いので、djb2 というハッシュで32bitの数にしてから16進8文字に
// する。djb2 がやっているのはこれだけ。
//
//     hash = 5381
//     文字ごとに  hash = hash * 33 + その文字のコード
//
// 33倍して足すだけだが、1文字違うだけで結果が大きく変わる。復元できない
// ことも、当てにくいことも、ここでは要らない（秘密を隠すのではなく、
// 長い文字列を短い名前に置き換えたいだけ）ので、この程度で足りる。
//
// JavaScript の数は 2^53 を超えると精度が落ちる。33倍を繰り返すとすぐ
// 超えるので、`| 0` で毎回32bitの符号付き整数に切り詰めてから次へ進む。
// 最後に `>>> 0` で符号なしに直し、16進にして0で8桁に埋める。
//
// 掛け算を32bitに丸めながら進めるので、同じ文字列からは環境によらず
// 必ず同じ値が出る。ビルドのたびに計算し直しても id は変わらない。
//
//
// ■ なぜ8文字か
//
// 実データで決めた。234フィード・23,723話に当てて、番組の中でも全番組を
// 通しても衝突が無かった（6文字だと5,172件ぶつかる）。32bitなので、
// 1番組1300話でも重なる見込みは 0.02% ほど。
//
// それでも起こりうるので、fetch-feeds は同じ番組の中で id が重なったら
// 警告を出す（/errors に出る）。
//
// もっと長い id が要るようになったら、初期値（5381）を変えてもう一度
// まわし、つないでから切り出せば伸ばせる。ただし**畳み方を変えると、
// それまでに配ったリンクが全部よそを指す**。lib/episode-id.test.js に
// 実際に出る値を書き留めてあるので、変えるとそこが落ちる。

// 16進8文字ぶん。djb2 ひとまわしが 32bit = 16進8文字なので、ここは
// 8以下であること（超えるなら上に書いたとおり二度まわす必要がある）
const ID_LENGTH = 8

export default function episodeId(value) {
  const source = String(value ?? '').trim()
  if(!source) return null

  let hash = 5381
  for(let i = 0; i < source.length; i++) {
    // hash * 33 + 文字コード。33倍は「32倍して1回足す」なので << 5 と +
    hash = ((hash << 5) + hash + source.charCodeAt(i)) | 0
  }
  return (hash >>> 0).toString(16).padStart(8, '0').slice(0, ID_LENGTH)
}
